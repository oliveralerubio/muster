//! `skills.lock`: provenance of every skill in the config repo (committed).
//!
//! ```toml
//! [[skill]]
//! name = "pdf"
//! origin = "anthropic"          # "local" for own skills
//! commit = "<upstream sha>"     # external skills only
//! content_hash = "sha256:<hex>"
//! version = "1.0.0"             # SKILL.md frontmatter `version`, if any
//! updated_at = "2026-10-14T12:00:00Z"
//! ```

use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::errors::MusterError;

pub const FILE_NAME: &str = "skills.lock";
pub const LOCAL: &str = "local";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockEntry {
    pub name: String,
    pub origin: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub commit: Option<String>,
    pub content_hash: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub version: Option<String>,
    pub updated_at: String,
}

impl LockEntry {
    pub fn is_local(&self) -> bool {
        self.origin == LOCAL
    }
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SkillsLock {
    #[serde(default, rename = "skill", skip_serializing_if = "Vec::is_empty")]
    pub skills: Vec<LockEntry>,
}

pub fn path(config_dir: &Path) -> PathBuf {
    config_dir.join(FILE_NAME)
}

/// Skill names follow the Agent Skills convention: lowercase ASCII letters,
/// digits and '-', not starting with '-'. This also guarantees a name is a
/// single path component (no `/`, `\\`, `..`, NUL or control characters), so
/// `<skills_dir>/<name>` can never escape the skills directory.
pub fn is_valid_name(name: &str) -> bool {
    !name.is_empty()
        && !name.starts_with('-')
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

impl SkillsLock {
    /// Load `<config_dir>/skills.lock`; a missing file is an empty lock.
    pub fn load(config_dir: &Path) -> Result<Self, MusterError> {
        let path = path(config_dir);
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Self::default()),
            Err(e) => return Err(MusterError::Operational(format!("{}: {e}", path.display()))),
        };
        let lock: Self = toml::from_str(&text).map_err(|e| MusterError::InvalidConfig {
            message: format!("invalid {FILE_NAME}: {}", e.message()),
            path: Some(path.display().to_string()),
        })?;
        // A name is joined onto the skills directory: reject anything that is
        // not a single, plain path component (`../x`, `a/b`, NUL, ...).
        if let Some(bad) = lock.skills.iter().find(|s| !is_valid_name(&s.name)) {
            return Err(MusterError::InvalidConfig {
                message: format!(
                    "invalid {FILE_NAME}: skill name {:?} must use lowercase letters, digits and '-'",
                    bad.name
                ),
                path: Some(path.display().to_string()),
            });
        }
        Ok(lock)
    }

    pub fn save(&mut self, config_dir: &Path) -> Result<(), MusterError> {
        self.skills.sort_by(|a, b| a.name.cmp(&b.name));
        let path = path(config_dir);
        let body = toml::to_string_pretty(self)
            .map_err(|e| MusterError::Operational(format!("cannot serialize {FILE_NAME}: {e}")))?;
        let text = format!(
            "# Generated by `muster skill`: provenance of every skill. Do not edit by hand.\n{body}"
        );
        crate::manifest::write_atomic(&path, text.as_bytes())
            .map_err(|e| MusterError::Operational(format!("{}: {e}", path.display())))
    }

    pub fn get(&self, name: &str) -> Option<&LockEntry> {
        self.skills.iter().find(|s| s.name == name)
    }

    /// Insert or replace the entry named `entry.name`.
    pub fn upsert(&mut self, entry: LockEntry) {
        debug_assert!(is_valid_name(&entry.name), "invalid skill name");
        match self.skills.iter_mut().find(|s| s.name == entry.name) {
            Some(existing) => *existing = entry,
            None => self.skills.push(entry),
        }
    }

    pub fn remove(&mut self, name: &str) -> Option<LockEntry> {
        let index = self.skills.iter().position(|s| s.name == name)?;
        Some(self.skills.remove(index))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lock_round_trips_and_sorts_by_name() {
        let dir = tempfile::TempDir::new().unwrap();
        let mut lock = SkillsLock::default();
        lock.upsert(LockEntry {
            name: "zeta".into(),
            origin: LOCAL.into(),
            commit: None,
            content_hash: "sha256:00".into(),
            version: None,
            updated_at: "2026-01-01T00:00:00Z".into(),
        });
        lock.upsert(LockEntry {
            name: "alpha".into(),
            origin: "anthropic".into(),
            commit: Some("abc".into()),
            content_hash: "sha256:11".into(),
            version: Some("1.0.0".into()),
            updated_at: "2026-01-01T00:00:00Z".into(),
        });
        lock.save(dir.path()).unwrap();
        let loaded = SkillsLock::load(dir.path()).unwrap();
        assert_eq!(loaded.skills[0].name, "alpha");
        assert_eq!(loaded, lock);
        assert!(SkillsLock::load(&dir.path().join("missing"))
            .unwrap()
            .skills
            .is_empty());
    }

    #[test]
    fn load_rejects_path_traversal_names() {
        for bad in ["../../etc", "a/b", "a\\\\b", "..", "x\\u0000y", "-x", ""] {
            let dir = tempfile::TempDir::new().unwrap();
            let text = format!(
                "[[skill]]\nname = \"{bad}\"\norigin = \"local\"\n\
                 content_hash = \"sha256:00\"\nupdated_at = \"2026-01-01T00:00:00Z\"\n"
            );
            std::fs::write(path(dir.path()), text).unwrap();
            assert!(
                matches!(
                    SkillsLock::load(dir.path()),
                    Err(MusterError::InvalidConfig { .. })
                ),
                "{bad:?} must be rejected"
            );
        }
    }

    #[test]
    fn save_is_atomic_and_leaves_no_temp_file() {
        let dir = tempfile::TempDir::new().unwrap();
        SkillsLock::default().save(dir.path()).unwrap();
        let names: Vec<_> = std::fs::read_dir(dir.path())
            .unwrap()
            .map(|e| e.unwrap().file_name().into_string().unwrap())
            .collect();
        assert_eq!(names, vec![FILE_NAME.to_string()]);
    }
}
